def read(path):
    with io.open(path, encoding="utf-8-sig") as handle:
        return handle.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = None
    if os.path.isfile(path):
        old = read(path)
    if old == text:
        return False
    with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return True


def strip_comments(text):
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == '"':
            if text.startswith('"""', i):
                j = text.find('"""', i + 3)
                j = n if j < 0 else j + 3
                out.append(text[i:j])
                i = j
                continue
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append(text[i:j + 1])
            i = j + 1
            continue
        if text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        if text.startswith("/*", i):
            j = text.find("*/", i + 2)
            out.append(" ")
            i = n if j < 0 else j + 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def split_top(text):
    parts = []
    depth = 0
    cur = []
    in_string = False
    i = 0
    while i < len(text):
        c = text[i]
        if in_string:
            cur.append(c)
            if c == "\\":
                i += 1
                cur.append(text[i])
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
            cur.append(c)
        elif c in "(<[":
            depth += 1
            cur.append(c)
        elif c in ")>]":
            depth -= 1
            cur.append(c)
        elif c == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail:
        parts.append(tail)
    return [p for p in parts if p]


def matching_paren(text, start):
    depth = 0
    i = start
    in_string = False
    while i < len(text):
        c = text[i]
        if in_string:
            if c == "\\":
                i += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise SystemExit("unbalanced parentheses")


def parse_fields(body, where):
    fields = []
    for part in split_top(body):
        m = re.match(r"val\s+(\w+)\s*:\s*([\w<>, ]+?)\s*=\s*(.+)$", part, re.S)
        if not m:
            raise SystemExit("%s: every property needs the form 'val name: Type = default' (got: %s)" % (where, part))
        name, ktype, default = m.group(1), re.sub(r"\s+", "", m.group(2)), m.group(3).strip()
        fields.append({"name": name, "type": ktype, "default": default})
    return fields


def parse_dtos():
    folder = os.path.join(CORE_SRC, "dto")
    enums = []
    structs = []
    channels = []
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".kt"):
            continue
        text = strip_comments(read(os.path.join(folder, name)))
        for m in re.finditer(r"enum\s+class\s+(\w+)\s*\{([^}]*)\}", text):
            values = [v.strip() for v in m.group(2).replace(";", ",").split(",") if v.strip()]
            enums.append({"name": m.group(1), "values": values})
        for m in re.finditer(r"@Serializable\s+data\s+class\s+(\w+)\s*\(", text):
            end = matching_paren(text, m.end() - 1)
            structs.append({"name": m.group(1), "fields": parse_fields(text[m.end():end], m.group(1))})
        for m in re.finditer(r'val\s+(\w+)\s*=\s*ChannelSpec\(\s*(\d+)\s*,\s*"(\w+)"\s*,\s*ChannelKind\.(\w+)\s*,\s*"(\w*)"\s*\)', text):
            channels.append({"const": m.group(1), "id": int(m.group(2)), "name": m.group(3), "kind": m.group(4), "dto": m.group(5)})
    channels.sort(key=lambda c: c["id"])
    names = {s["name"] for s in structs}
    for s in structs:
        for f in s["fields"]:
            if f["name"] in CPP_RESERVED:
                raise SystemExit("%s.%s: the name is a C++ keyword or a Windows macro, pick another" % (s["name"], f["name"]))
            inner = list_inner(f["type"])
            base = inner or f["type"]
            if base not in PRIMITIVES and base not in names:
                raise SystemExit("%s.%s: type %s is not allowed in a DTO" % (s["name"], f["name"], f["type"]))
            check_default(s["name"], f)
    return enums, order_structs(structs), channels


def list_inner(ktype):
    m = re.match(r"List<(\w+)>$", ktype)
    return m.group(1) if m else None


def check_default(owner, field):
    t = field["type"]
    d = field["default"]
    ok = (
        (t == "String" and d == '""') or (t == "Int" and d == "0") or (t == "Boolean" and d == "false")
        or (t == "Float" and d == "0f") or (t.startswith("List<") and d == "emptyList()")
        or (t.endswith("Dto") and not t.startswith("List<") and d == t + "()")
    )
    if not ok:
        raise SystemExit("%s.%s: the default must be the zero value of %s (got %s)" % (owner, field["name"], t, d))


def order_structs(structs):
    by_name = {s["name"]: s for s in structs}
    done = []
    seen = set()

    def visit(s):
        if s["name"] in seen:
            return
        seen.add(s["name"])
        for f in s["fields"]:
            base = list_inner(f["type"]) or f["type"]
            if base in by_name:
                visit(by_name[base])
        done.append(s)

    for s in structs:
        visit(s)
    return done


def parse_actions():
    text = strip_comments(read(os.path.join(CORE_SRC, "actions", "UiAction.kt")))
    actions = []
    for m in re.finditer(r'@SerialName\("(\w+)"\)\s+data\s+(class|object)\s+(\w+)', text):
        serial, kind, name = m.group(1), m.group(2), m.group(3)
        if serial != name:
            raise SystemExit("UiAction.%s: @SerialName must equal the class name" % name)
        params = []
        if kind == "class":
            start = text.index("(", m.end())
            end = matching_paren(text, start)
            for f in parse_fields(text[start + 1:end], "UiAction." + name):
                if f["type"] not in PRIMITIVES:
                    raise SystemExit("UiAction.%s.%s: type %s is not allowed" % (name, f["name"], f["type"]))
                if f["name"] in CPP_RESERVED:
                    raise SystemExit("UiAction.%s.%s: the name is a C++ keyword or a Windows macro, pick another" % (name, f["name"]))
                params.append(f)
        actions.append({"name": name, "params": params})
    return actions


def interface_body(text, name):
    m = re.search(r"\binterface\s+" + re.escape(name) + r"\b[^{]*\{", text)
    if not m:
        raise SystemExit("interface %s not found" % name)
    depth = 1
    i = m.end()
    while i < len(text) and depth:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    return text[m.end():i - 1]


def parse_strings():
    body = interface_body(strip_comments(read(os.path.join(I18N, "AppLocalization.kt"))), "AppLocalization")
    names = [m.group(1) for m in re.finditer(r"\bval\s+(\w+)\s*:\s*String\b", body)]
    english = strip_comments(read(os.path.join(I18N, "EnglishProvider.kt")))
    defaults = {}
    pattern = re.compile(r'override\s+val\s+(\w+)\s*(?::\s*String\s*)?=\s*((?:"(?:[^"\\\n]|\\.)*"\s*\+?\s*)+)')
    for name, literal in pattern.findall(english):
        pieces = re.findall(r'"((?:[^"\\\n]|\\.)*)"', literal)
        defaults[name] = kotlin_unescape("".join(pieces))
    return names, defaults


def kotlin_unescape(text):
    out = []
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            e = text[i + 1]
            if e == "u":
                out.append(chr(int(text[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append({"n": "\n", "t": "\t", "r": "\r", "b": "\b"}.get(e, e))
            i += 2
            continue
        out.append(c)
        i += 1
    return "".join(out)


def slint_string(text):
    out = ['"']
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append(" ")
        elif c == "{":
            out.append("{")
        else:
            out.append(c)
    out.append('"')
    return "".join(out)


def kebab(name):
    return name.lower().replace("_", "-")


def slint_type(ktype):
    inner = list_inner(ktype)
    if inner:
        return "[" + PRIMITIVES.get(inner, inner) + "]"
    return PRIMITIVES.get(ktype, ktype)


def tr_slint_name(name):
    return name + "Text" if name in SLINT_RESERVED else name


def camel(value):
    return "".join(part[:1].upper() + part[1:].lower() for part in value.split("_"))


def lower_first(name):
    return name[0].lower() + name[1:]


def gen_dto_slint(enums, structs, channels):
    lines = ["// " + HEADER, ""]
    for s in structs:
        lines.append("export struct %s {" % s["name"])
        for f in s["fields"]:
            lines.append("    %s: %s," % (f["name"], slint_type(f["type"])))
        lines.append("}")
        lines.append("")
    for e in enums:
        if e["name"] in ("ChannelKind",):
            continue
        lines.append("export global %s {" % e["name"])
        for index, value in enumerate(e["values"]):
            lines.append("    out property <int> %s: %d;" % (kebab(value), index))
        lines.append("}")
        lines.append("")
    lines.append("export global Core {")
    for c in channels:
        if c["kind"] == "STRUCT":
            lines.append("    in property <%s> %s;" % (c["dto"], c["name"]))
        elif c["kind"] == "LIST":
            lines.append("    in property <[%s]> %s;" % (c["dto"], c["name"]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_actions_slint(actions):
    lines = ["// " + HEADER, "", "export global Act {"]
    for a in actions:
        params = ", ".join("%s: %s" % (p["name"], PRIMITIVES[p["type"]]) for p in a["params"])
        lines.append("    callback %s(%s);" % (lower_first(a["name"]), params))
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_tr_slint(names, defaults):
    lines = ["// " + HEADER, "", "export global Tr {", '    in property <string> lang: "en";']
    for name in names:
        lines.append("    in property <string> %s: %s;" % (tr_slint_name(name), slint_string(defaults.get(name, ""))))
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_tr_kotlin(names):
    lines = [
        "// " + HEADER,
        "package com.michelle.raouf.fetch_jet.nativeapp.generated",
        "",
        "import com.michelle.raouf.fetch_jet.core.i18n.data_provider.AppLocalization",
        "",
        "internal const val TR_COUNT = %d" % len(names),
        "",
        "internal fun trValues(s: AppLocalization): List<String> = listOf(",
    ]
    for name in names:
        lines.append("    s.%s," % name)
    lines.append(")")
    return "\n".join(lines) + "\n"


def cpp_field_parse(f, structs_by_name):
    name = f["name"]
    t = f["type"]
    inner = list_inner(t)
    if t == "String":
        return 'd.%s = fj::text(j, "%s");' % (name, name)
    if t == "Int":
        return 'd.%s = fj::integer(j, "%s");' % (name, name)
    if t == "Float":
        return 'd.%s = fj::real(j, "%s");' % (name, name)
    if t == "Boolean":
        return 'd.%s = fj::flag(j, "%s");' % (name, name)
    if inner == "String":
        return 'd.%s = fj::text_model(j, "%s");' % (name, name)
    if inner == "Int":
        return 'd.%s = fj::int_model(j, "%s");' % (name, name)
    if inner in structs_by_name:
        return 'd.%s = fj::struct_model<%s>(j, "%s", parse_%s);' % (name, inner, name, inner)
    if t in structs_by_name:
        return 'd.%s = parse_%s(fj::child(j, "%s"));' % (name, t, name)
    raise SystemExit("no C++ rule for %s" % t)


def gen_cpp(enums, structs, channels, actions, names):
    by_name = {s["name"]: s for s in structs}
    out = ["// " + HEADER, "#pragma once", "", '#include "bridge_support.h"', "", "namespace fjgen {", ""]
    for e in enums:
        if e["name"] == "ChannelKind":
            continue
        out.append("namespace %s {" % e["name"])
        for index, value in enumerate(e["values"]):
            out.append("    inline constexpr int %s = %d;" % (camel(value), index))
        out.append("}")
        out.append("")
    out.append("namespace Channel {")
    for c in channels:
        out.append("    inline constexpr int %s = %d;" % (camel(c["const"]), c["id"]))
    out.append("    inline constexpr int Count = %d;" % (max(c["id"] for c in channels) + 1))
    out.append("}")
    out.append("")
    for s in structs:
        out.append("inline %s parse_%s(const fj::Json &j) {" % (s["name"], s["name"]))
        out.append("    %s d{};" % s["name"])
        for f in s["fields"]:
            out.append("    " + cpp_field_parse(f, by_name))
        out.append("    return d;")
        out.append("}")
        out.append("")
    out.append("struct Models {")
    for c in channels:
        if c["kind"] == "LIST":
            out.append("    std::shared_ptr<slint::VectorModel<%s>> %s = std::make_shared<slint::VectorModel<%s>>();" % (c["dto"], c["name"], c["dto"]))
    out.append("};")
    out.append("")
    out.append("inline void bind_models(const Core &core, const Models &models) {")
    for c in channels:
        if c["kind"] == "LIST":
            out.append("    core.set_%s(models.%s);" % (c["name"], c["name"]))
    out.append("}")
    out.append("")
    out.append("inline bool apply_channel(const Core &core, Models &models, int channel, const fj::Json &j) {")
    out.append("    switch (channel) {")
    for c in channels:
        if c["kind"] == "STRUCT":
            out.append("        case %d: core.set_%s(parse_%s(j)); return true;" % (c["id"], c["name"], c["dto"]))
        elif c["kind"] == "LIST":
            out.append("        case %d: fj::apply_rows<%s>(*models.%s, j, parse_%s); return true;" % (c["id"], c["dto"], c["name"], c["dto"]))
    out.append("        default: return false;")
    out.append("    }")
    out.append("}")
    out.append("")
    for c in channels:
        if c["kind"] == "QUEUE":
            out.append("inline std::vector<%s> parse_%s_queue(const fj::Json &j) {" % (c["dto"], c["name"]))
            out.append("    std::vector<%s> items;" % c["dto"])
            out.append("    for (const auto &item : j.items) items.push_back(parse_%s(item));" % c["dto"])
            out.append("    return items;")
            out.append("}")
            out.append("")
    out.append("inline void apply_tr(const Tr &tr, const fj::Json &j) {")
    out.append('    tr.set_lang(fj::text(j, "lang"));')
    out.append('    const fj::Json &values = fj::child(j, "values");')
    out.append("    size_t index = 0;")
    out.append("    auto next = [&]() { return index < values.items.size() ? slint::SharedString(values.items[index++].text) : slint::SharedString(); };")
    for name in names:
        out.append("    tr.set_%s(next());" % tr_slint_name(name))
    out.append("}")
    out.append("")
    out.append("template <class Send> void bind_actions(const Act &act, Send send) {")
    for a in actions:
        cpp_params = ", ".join("%s %s" % (CPP_TYPES[p["type"]], p["name"]) for p in a["params"])
        body = ['fj::ActionWriter w("%s");' % a["name"]]
        for p in a["params"]:
            body.append('w.add("%s", %s);' % (p["name"], p["name"]))
        body.append("send(w.finish());")
        out.append("    act.on_%s([send](%s) { %s });" % (lower_first(a["name"]), cpp_params, " ".join(body)))
    out.append("}")
    out.append("")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    enums, structs, channels = parse_dtos()
    actions = parse_actions()
    names, defaults = parse_strings()
    renamed = [n for n in names if tr_slint_name(n) != n]
    missing = [n for n in names if n not in defaults]
    outputs = {
        os.path.join(NATIVE, "ui", "generated", "dto.slint"): gen_dto_slint(enums, structs, channels),
        os.path.join(NATIVE, "ui", "generated", "actions.slint"): gen_actions_slint(actions),
        os.path.join(NATIVE, "ui", "generated", "tr.slint"): gen_tr_slint(names, defaults),
        os.path.join(CORE_SRC, "generated", "TrTable.kt"): gen_tr_kotlin(names),
        os.path.join(NATIVE, "host", "generated", "fj_bridge.h"): gen_cpp(enums, structs, channels, actions, names),
        os.path.join(NATIVE, "ui", "generated", "protocol.json"): json.dumps({
            "channels": channels,
            "enums": {e["name"]: e["values"] for e in enums},
            "structs": {s["name"]: [[f["name"], f["type"]] for f in s["fields"]] for s in structs},
            "actions": {a["name"]: [[p["name"], p["type"]] for p in a["params"]] for a in actions},
            "tr": [tr_slint_name(n) for n in names],
        }, indent=1, ensure_ascii=False) + "\n",
    }
    changed = 0
    for path, text in outputs.items():
        if write(path, text):
            changed += 1
            print("wrote " + os.path.relpath(path, REPO).replace("\\", "/"))
    print("%d structs, %d enums, %d channels, %d actions, %d strings (%d renamed: %s; %d without an English default)" % (
        len(structs), len(enums), len(channels), len(actions), len(names), len(renamed), ", ".join(renamed) or "-", len(missing)))
    if missing:
        print("no default: " + ", ".join(missing[:20]))
    if not changed:
        print("nothing changed")


if __name__ == "__main__":
    main()
